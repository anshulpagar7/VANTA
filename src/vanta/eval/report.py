"""Static HTML report generator.

The report IS the deliverable. It is generated by the eval run, committed, and
served from GitHub Pages, so a reviewer who will not clone and run the code
still sees the full result -- and a reviewer who does run it gets byte-identical
numbers.

No external services, no JS, no image files: one self-contained HTML file.
"""
from __future__ import annotations

import html
import pathlib
import sqlite3
import subprocess
from collections import defaultdict
from datetime import UTC, datetime
from statistics import mean, stdev

from vanta.eval.runner import RunStats

ARM_LABELS = {
    "A_naive": "A · naive fixed retry",
    "B_ladder": "B · deterministic rule ladder",
    "Bplus_vanta_norag": "B+ · VANTA scoring, no LLM",
    "C_vanta": "C · VANTA scoring + LLM diagnosis",
}

CSS = """
*{box-sizing:border-box}
body{font:15px/1.6 system-ui,-apple-system,Segoe UI,sans-serif;color:#1a1a1a;
 background:#fbfbfa;margin:0;padding:40px 24px}
main{max-width:900px;margin:0 auto}
h1{font-size:26px;font-weight:600;margin:0 0 4px}
h2{font-size:18px;font-weight:600;margin:38px 0 10px;padding-top:14px;border-top:1px solid #e5e3dd}
.sub{color:#66645e;margin:0 0 22px}
table{border-collapse:collapse;width:100%;font-size:14px;margin:8px 0 4px}
th{text-align:left;font-weight:600;color:#66645e;padding:7px 10px;border-bottom:1px solid #d8d6cf}
td{padding:7px 10px;border-bottom:1px solid #eeece6}
td.n,th.n{text-align:right;font-variant-numeric:tabular-nums}
.bar{height:7px;background:#3b6d5c;border-radius:2px;display:inline-block;vertical-align:middle}
.bar.muted{background:#b9b7ae}
.note{background:#fdf6e6;border-left:3px solid #d09a2c;padding:12px 16px;margin:16px 0;font-size:14px}
.warn{background:#fbeceb;border-left:3px solid #c0483c;padding:12px 16px;margin:16px 0;font-size:14px}
.delta{font-size:22px;font-weight:600;margin:6px 0}
code{background:#f0eee8;padding:1px 5px;border-radius:3px;font-size:13px}
footer{margin-top:44px;padding-top:14px;border-top:1px solid #e5e3dd;color:#8a887f;font-size:13px}
"""


def _rupees(paise: float) -> str:
    return f"₹{paise / 100:,.0f}"


def _ci95(xs: list[float]) -> float:
    return 1.96 * stdev(xs) / len(xs) ** 0.5 if len(xs) > 1 else 0.0


def _git(*args: str) -> str:
    try:
        return subprocess.run(["git", *args], capture_output=True, text=True,
                              timeout=5).stdout.strip() or "unknown"
    except Exception:
        return "unknown"


def _headline_table(results: dict[str, list[RunStats]]) -> str:
    rows = []
    peak = max(
        (mean(r.recovered_paise for r in runs) for runs in results.values()), default=1
    )
    for arm, runs in results.items():
        rec = [float(r.recovered_paise) for r in runs]
        m, ci = mean(rec), _ci95(rec)
        cpr = [r.contacts_per_recovery for r in runs if r.recovered_events]
        decs = [r.authorized + r.blocked + r.abstained + r.review_required for r in runs]
        absr = mean(r.abstained / d if d else 0 for r, d in zip(runs, decs, strict=True))
        eff = mean(r.efficiency for r in runs if r.intervention_cost_paise) if any(
            r.intervention_cost_paise for r in runs) else float("inf")
        width = int(200 * m / peak) if peak else 0
        rows.append(
            f"<tr><td>{html.escape(ARM_LABELS.get(arm, arm))}"
            f"<br><span class='bar' style='width:{width}px'></span></td>"
            f"<td class='n'>{_rupees(m)} <span style='color:#8a887f'>± {_rupees(ci)}</span></td>"
            f"<td class='n'>{mean(r.recovery_rate for r in runs):.1%}</td>"
            f"<td class='n'>{(mean(cpr) if cpr else 0):.2f}</td>"
            f"<td class='n'>{'—' if eff == float('inf') else f'{eff:,.0f}×'}</td>"
            f"<td class='n'>{absr:.1%}</td>"
            f"<td class='n'>{mean(r.blocked for r in runs):,.0f}</td></tr>"
        )
    return (
        "<table><tr><th>arm</th><th class='n'>₹ recovered (mean ± 95% CI)</th>"
        "<th class='n'>rate</th><th class='n'>contacts/rec</th>"
        "<th class='n'>₹ per ₹ spent</th><th class='n'>abstain</th>"
        "<th class='n'>blocked</th></tr>" + "".join(rows) + "</table>"
    )


def _ablation(results: dict[str, list[RunStats]]) -> str:
    b, c = results.get("Bplus_vanta_norag"), results.get("C_vanta")
    if not (b and c):
        return ("<div class='warn'><b>Arm C has no result.</b> The diagnosis cache is not "
                "built, so the LLM's contribution is unmeasured. Run "
                "<code>vanta build-cache</code>.</div>")
    bm = mean(r.recovered_paise for r in b)
    cm = mean(r.recovered_paise for r in c)
    delta, pct = cm - bm, (cm - bm) / bm if bm else 0
    verdict = ("the LLM earns its place" if delta > 0 else
               "the deterministic map matches or beats the LLM on this task")
    return (
        f"<p class='delta'>C − B+ = {_rupees(delta)} ({pct:+.1%})</p>"
        f"<p>Both arms run identical scoring, candidates, scheduling and abstention "
        f"logic. The only difference is where the diagnosis comes from, so this "
        f"number is the language model's isolated contribution — on these seeds, "
        f"<b>{verdict}</b>.</p>"
    )


def _by_slug(conn: sqlite3.Connection, arm: str) -> str:
    rows = conn.execute(
        "SELECT reason_slug, SUM(recovered_paise), COUNT(*), "
        "SUM(outcome='abstained') FROM audit WHERE arm=? GROUP BY reason_slug "
        "ORDER BY 2 DESC", (arm,)).fetchall()
    if not rows:
        return "<p>No audit rows.</p>"
    body = "".join(
        f"<tr><td><code>{html.escape(s)}</code></td><td class='n'>{_rupees(rec or 0)}</td>"
        f"<td class='n'>{n:,}</td><td class='n'>{ab:,}</td></tr>"
        for s, rec, n, ab in rows
    )
    return ("<table><tr><th>failure reason</th><th class='n'>₹ recovered</th>"
            "<th class='n'>decisions</th><th class='n'>abstentions</th></tr>"
            + body + "</table>")


def _provider_mix_section() -> str:
    """Arm C's diagnoses may come from more than one model if a fallback chain
    was used. Stating the mix is not optional: an ensemble described as a
    single model would misattribute the ablation result."""
    try:
        from vanta.diagnosis.cache import DiagnosisCache
        mix = DiagnosisCache().provider_mix()
    except Exception:
        return ""
    if not mix:
        return ""
    items = ", ".join(f"<code>{html.escape(k)}</code> {v}" for k, v in sorted(mix.items()))
    warn = ""
    if len([k for k in mix if k != "rules-fallback"]) > 1:
        warn = ("<div class='warn'><b>Arm C is a mixed ensemble.</b> More than one "
                "model produced these diagnoses, so C − B+ measures the blend, not "
                "a single model.</div>")
    if "rules-fallback" in mix:
        warn += ("<div class='warn'><b>Some buckets fell back to rules-based "
                 "diagnosis.</b> Those decisions are arm B+ logic wearing arm C's "
                 "label and inflate the apparent similarity of the two arms.</div>")
    return f"<h2>Diagnosis provenance</h2><p>{items}</p>{warn}"


def _blocks(results: dict[str, list[RunStats]]) -> str:
    agg: dict[str, dict[str, int]] = defaultdict(lambda: defaultdict(int))
    for arm, runs in results.items():
        for r in runs:
            for k, v in r.block_reasons.items():
                agg[arm][k] += v
    if not any(agg.values()):
        return "<p>No actions were refused: every policy proposed only permitted actions.</p>"
    out = []
    for arm, reasons in agg.items():
        if not reasons:
            continue
        items = ", ".join(f"<code>{html.escape(k)}</code> {v:,}"
                          for k, v in sorted(reasons.items(), key=lambda x: -x[1]))
        out.append(f"<p><b>{html.escape(ARM_LABELS.get(arm, arm))}</b> — {items}</p>")
    return "".join(out)


def _traces(conn: sqlite3.Connection, arm: str, limit: int = 3) -> str:
    ids = [r[0] for r in conn.execute(
        "SELECT event_id FROM audit WHERE arm=? GROUP BY event_id "
        "HAVING COUNT(*)>2 LIMIT ?", (arm, limit)).fetchall()]
    conn.row_factory = sqlite3.Row
    out = []
    for eid in ids:
        rows = conn.execute("SELECT * FROM audit WHERE arm=? AND event_id=? ORDER BY id",
                            (arm, eid)).fetchall()
        body = "".join(
            f"<tr><td>{html.escape(r['decided_at'][:16])}</td>"
            f"<td><code>{html.escape(r['requested_action'])}</code></td>"
            f"<td>{html.escape(r['outcome'])}"
            + (f" — <code>{html.escape(r['block_reason'])}</code>" if r["block_reason"] else "")
            + f"</td><td class='n'>{_rupees(r['recovered_paise'])}</td>"
            f"<td style='color:#66645e'>{html.escape((r['rationale'] or '')[:70])}</td></tr>"
            for r in rows
        )
        out.append(
            f"<p style='margin-bottom:2px'><code>{html.escape(eid)}</code> "
            f"({html.escape(rows[0]['reason_slug'])}, {_rupees(rows[0]['amount_paise'])})</p>"
            f"<table><tr><th>when</th><th>action</th><th>outcome</th>"
            f"<th class='n'>recovered</th><th>why</th></tr>{body}</table>"
        )
    conn.row_factory = None
    return "".join(out) or "<p>No multi-step episodes found.</p>"


def generate(
    results: dict[str, list[RunStats]],
    suite: str,
    n_events: int,
    seeds: tuple[int, ...],
    audit_path: str | None = None,
    out_path: pathlib.Path = pathlib.Path("results/report.html"),
) -> pathlib.Path:
    conn = sqlite3.connect(audit_path) if audit_path else None
    focus = "C_vanta" if "C_vanta" in results else "Bplus_vanta_norag"

    dev_warning = (
        "<div class='note'><b>These are development numbers.</b> Policies were tuned "
        "against these seeds, so this table measures fit, not performance. The result "
        "is the holdout run, which happens once after the policy freeze (ADR-003).</div>"
        if suite == "development" else
        "<div class='note'><b>Holdout run.</b> Policies were frozen before these seeds "
        "were touched. This table is the result; it was not re-run.</div>"
    )

    parts = [
        f"<!doctype html><meta charset='utf-8'><title>VANTA — {suite} results</title>",
        f"<style>{CSS}</style><main>",
        "<h1>VANTA</h1>",
        "<p class='sub'>Verified Authority for Transaction Actions — "
        "a benchmark for agentic revenue recovery.</p>",
        dev_warning,
        "<h2>Results</h2>", _headline_table(results),
        "<p style='color:#66645e;font-size:13px'>Abstention is a first-class outcome: "
        "declining to spend customer attention where expected return is low is the "
        "system working, not failing.</p>",
        "<h2>The ablation</h2>", _ablation(results),
        "<h2>Guardrail activity</h2>", _blocks(results),
        _provider_mix_section(),
    ]
    if conn:
        parts += [
            f"<h2>Where the money came from — {html.escape(ARM_LABELS.get(focus, focus))}</h2>",
            _by_slug(conn, focus),
            "<h2>Decision traces</h2>",
            "<p style='color:#66645e;font-size:13px'>Every decision, including refusals "
            "and abstentions, is written to an append-only audit log.</p>",
            _traces(conn, focus),
        ]
    parts += [
        "<h2>Honesty</h2>",
        "<p>Known limitations, unmodelled effects and parameter provenance are in "
        "<code>LIMITATIONS.md</code>. Assumed cost values are in <code>costs.yaml</code> "
        "and are swept in the sensitivity analysis.</p>",
        f"<footer>suite <b>{html.escape(suite)}</b> · seeds {seeds} · "
        f"{n_events:,} events per seed · world <code>{_git('describe','--tags','--always')}</code> · "
        f"commit <code>{_git('rev-parse','--short','HEAD')}</code> · "
        f"generated {datetime.now(UTC):%Y-%m-%d %H:%M} UTC</footer></main>",
    ]
    out_path.parent.mkdir(parents=True, exist_ok=True)
    # Explicit UTF-8: pathlib defaults to the platform encoding, which is
    # cp1252 on Windows and cannot encode the rupee sign. Never rely on locale
    # for a file whose content is fixed.
    out_path.write_text("".join(parts), encoding="utf-8")
    if conn:
        conn.close()
    return out_path
